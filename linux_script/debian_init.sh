get_recommended_zram_percent() {
    # Calculate recommended zram percentage based on RAM size
    # Smaller RAM needs higher percentage to have usable swap
    local mem_mb=$1
    if [ "$mem_mb" -le 512 ]; then
        echo 150   # 512MB RAM → 768MB zram (compression makes it ~1.5-3GB effective)
    elif [ "$mem_mb" -le 1024 ]; then
        echo 100   # 1GB RAM → 1GB zram
    elif [ "$mem_mb" -le 2048 ]; then
        echo 75    # 2GB RAM → 1.5GB zram
    elif [ "$mem_mb" -le 4096 ]; then
        echo 50    # 4GB RAM → 2GB zram
    else
        echo 25    # 8GB+ RAM → 25% is enough
    fi
}

configure_zram() {
    local percent="$1"
    local mem_mb="$2"
    local zram_size_mb=$((mem_mb * percent / 100))
    
    # Ensure zram-tools is installed
    if ! dpkg -l zram-tools 2>/dev/null | grep -q "^ii"; then
        print_info "Installing zram-tools..."
        apt-get install $APT_INSTALL_OPTS zram-tools
    fi
    
    # Stop service first
    systemctl stop zramswap.service 2>/dev/null || true
    
    # Write configuration
    cat > /etc/default/zramswap <<EOF
# zramswap config managed by init script
ALGO=lz4
PERCENT=${percent}
PRIORITY=100
EOF
    
    # Start with new config
    systemctl enable --now zramswap.service 2>/dev/null || true
    
    print_success "zram configured: ${percent}% of RAM (~${zram_size_mb}MB, lz4 compressed)"
}

maybe_enable_zram_swap() {
    local has_zram=0 has_disk_swap=0 disk_swap_info=""
    local mem_mb current_zram_mb current_percent recommended_percent
    
    mem_mb=$((MEM_KB / 1024))
    recommended_percent=$(get_recommended_zram_percent "$mem_mb")
    local recommended_size_mb=$((mem_mb * recommended_percent / 100))
    
    # Check current swap status
    if grep -q "^/dev/zram" /proc/swaps 2>/dev/null; then
        has_zram=1
        current_zram_mb=$(awk '$1 ~ /zram/ {s+=$3} END {printf "%.0f", s/1024}' /proc/swaps)
    fi
    # Check for non-zram swap (disk partition or swap file)
    if awk 'NR>1 && $1 !~ /zram/ {found=1} END {exit !found}' /proc/swaps 2>/dev/null; then
        has_disk_swap=1
        disk_swap_info=$(awk 'NR>1 && $1 !~ /zram/ {printf "%s (%d MB) ", $1, $3/1024}' /proc/swaps)
    fi
    
    # Case 1: Already has zram → offer to adjust size
    if [ "$has_zram" -eq 1 ]; then
        current_percent=$((current_zram_mb * 100 / mem_mb))
        print_info "zram swap active: ${current_zram_mb}MB (~${current_percent}% of RAM)"
        print_info "Recommended for ${mem_mb}MB RAM: ${recommended_percent}% (~${recommended_size_mb}MB)"
        
        # Only offer change if current differs significantly from recommended
        local diff=$((current_percent - recommended_percent))
        [ "$diff" -lt 0 ] && diff=$((-diff))
        
        if [ "$diff" -ge 15 ]; then
            echo -ne "${BOLD}Adjust zram to recommended ${recommended_percent}%? [y/N]: ${RESET}"
            read -r ans
            if [[ "$ans" =~ ^[Yy]$ ]]; then
                configure_zram "$recommended_percent" "$mem_mb"
            else
                print_info "Keeping current zram configuration."
            fi
        else
            print_info "Current zram size is reasonable; no change needed."
        fi
        return
    fi
    
    # Case 2: Has disk swap but no zram → offer to add zram (coexist)
    if [ "$has_disk_swap" -eq 1 ]; then
        print_info "Disk swap detected: ${disk_swap_info}"
        print_info "Recommended zram for ${mem_mb}MB RAM: ${recommended_percent}% (~${recommended_size_mb}MB)"
        echo -ne "${BOLD}Add zram swap alongside disk swap? (zram will be used first, priority=100) [y/N]: ${RESET}"
        read -r ans
        if [[ ! "$ans" =~ ^[Yy]$ ]]; then
            print_info "Keeping disk swap only."
            return
        fi
        configure_zram "$recommended_percent" "$mem_mb"
        print_info "zram coexists with disk swap (zram priority=100, used first)"
        return
    fi
    
    # Case 3: No swap at all → offer zram
    print_info "No swap detected."
    print_info "Recommended zram for ${mem_mb}MB RAM: ${recommended_percent}% (~${recommended_size_mb}MB)"
    echo -ne "${BOLD}Enable zram swap? [y/N]: ${RESET}"
    read -r ans
    if [[ ! "$ans" =~ ^[Yy]$ ]]; then
        print_info "Skipping zram swap setup."
        return
    fi
    configure_zram "$recommended_percent" "$mem_mb"
}

backup_other_sysctl() {
    # Backup non-script-generated sysctl configs to a timestamped folder
    # This disables them (by moving out of sysctl.d) while preserving for reference
    if [ -z "$OTHER_SYSCTL_FILES" ]; then
        return
    fi
    
    local backup_dir="/etc/sysctl.d/bak-utc-${SCRIPT_TIMESTAMP}"
    local backed_up=0
    
    for f in $OTHER_SYSCTL_FILES; do
        [ -f "$f" ] || continue
        
        # Create backup directory if needed
        if [ "$backed_up" -eq 0 ]; then
            mkdir -p "$backup_dir"
            print_info "Backing up existing sysctl configs to $backup_dir"
        fi
        
        local basename
        basename=$(basename "$f")
        
        if [ "$f" = "/etc/sysctl.conf" ]; then
            # Special handling for /etc/sysctl.conf - copy and clear
            cp "$f" "${backup_dir}/sysctl.conf.bak"
            # Clear the file but keep it (some systems expect it to exist)
            cat > "$f" <<EOF
# Cleared by debian_init.sh on ${SCRIPT_TIMESTAMP} UTC
# Original backed up to: ${backup_dir}/sysctl.conf.bak
EOF
            echo -e "  ${YELLOW}•${RESET} /etc/sysctl.conf → ${backup_dir}/sysctl.conf.bak (cleared)"
        else
            # Move .conf files to backup dir with .bak extension
            mv "$f" "${backup_dir}/${basename}.bak"
            echo -e "  ${YELLOW}•${RESET} $f → ${backup_dir}/${basename}.bak"
        fi
        backed_up=$((backed_up + 1))
    done
    
    if [ "$backed_up" -gt 0 ]; then
        print_success "Backed up $backed_up config(s) - old settings disabled"
    fi
}

write_marker() {
    mkdir -p "$(dirname "$MARKER_FILE")"
    {
        echo "# Marker for debian_init.sh"
        echo "# Indicates 99-network-tuning.conf has been applied"
        echo "timestamp_utc: ${SCRIPT_TIMESTAMP}"
    } > "$MARKER_FILE"
    print_info "Marker written to: $MARKER_FILE"
}

show_report() {
    print_banner "${ICON_DOC} Summary"
    print_kv "BBR" "$(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null || echo '?')"
    print_kv "Queueing" "$(sysctl -n net.core.default_qdisc 2>/dev/null || echo '?')"
    print_kv "swappiness" "$(sysctl -n vm.swappiness 2>/dev/null || echo '?')"
    print_kv "IP forwarding" "$(sysctl -n net.ipv4.ip_forward 2>/dev/null | grep -q 1 && echo 'enabled' || echo 'disabled')"
    print_kv "IPv6" "$(sysctl -n net.ipv6.conf.all.disable_ipv6 2>/dev/null | grep -q 1 && echo 'disabled' || echo 'enabled')"
    echo ""
    print_info "sysctl configs:"
    [ -f "$SYSCTL_NETWORK_FILE" ] && echo -e "  ${GREEN}•${RESET} $SYSCTL_NETWORK_FILE"
    [ -f "$SYSCTL_SWAPPINESS_FILE" ] && echo -e "  ${GREEN}•${RESET} $SYSCTL_SWAPPINESS_FILE"
    [ -f "$SYSCTL_FORWARDING_FILE" ] && echo -e "  ${GREEN}•${RESET} $SYSCTL_FORWARDING_FILE"
    [ -f "$SYSCTL_IPV6_FILE" ] && echo -e "  ${GREEN}•${RESET} $SYSCTL_IPV6_FILE"
    echo ""
    if [ "$EZA_VER" != "Not installed" ]; then
        print_kv "Eza" "$EZA_VER (use: ls, ll, la, tree)"
    else
        print_kv "Eza" "$EZA_VER"
    fi
    if [ "$HELIX_VER" != "Not installed" ]; then
        print_kv "Helix" "$HELIX_VER (use: vi, vim, hx)"
    else
        print_kv "Helix" "$HELIX_VER"
    fi
    if [ "$SPEEDTEST_VER" != "Not installed" ]; then
        print_kv "Speedtest" "$SPEEDTEST_VER (use: speedtest)"
    else
        print_kv "Speedtest" "$SPEEDTEST_VER"
    fi
    print_kv "chrony" "$(systemctl is-active chrony 2>/dev/null || echo '?')"
    print_kv "fail2ban" "$(systemctl is-active fail2ban 2>/dev/null || echo '?')"
    if command_exists unattended-upgrade; then
        print_kv "unattended-upgrades" "installed ($(systemctl is-active apt-daily-upgrade.timer 2>/dev/null || echo 'timer?'))"
    else
        print_kv "unattended-upgrades" "not installed"
    fi
    print_kv "zram swap" "${ZRAM_STATUS:-not detected}"
    print_kv "Docker" "$DOCKER_STATUS"
    print_kv "Timezone" "${TIMEZONE_FINAL:-unknown}"
    print_kv "Marker" "$MARKER_FILE"
    echo ""
    print_success "All steps complete. Reboot recommended for full effect."
}

