detect_existing_sysctl() {
    EXISTING_SYSCTL_SETTINGS=""
    local found_files=""
    local script_files=""
    local other_files=""
    local key_settings=""
    local script_marker="Generated by: debian_init.sh"
    
    # Check /etc/sysctl.conf
    if [ -f /etc/sysctl.conf ]; then
        local conf_settings
        conf_settings=$(grep -v '^#' /etc/sysctl.conf 2>/dev/null | grep -v '^$' | grep '=' || true)
        if [ -n "$conf_settings" ]; then
            found_files="${found_files}/etc/sysctl.conf "
            other_files="${other_files}/etc/sysctl.conf "
            key_settings="${key_settings}${conf_settings}\n"
        fi
    fi
    
    # Check /etc/sysctl.d/*.conf
    if [ -d /etc/sysctl.d ]; then
        for f in /etc/sysctl.d/*.conf; do
            [ -f "$f" ] || continue
            local file_settings
            file_settings=$(grep -v '^#' "$f" 2>/dev/null | grep -v '^$' | grep '=' || true)
            if [ -n "$file_settings" ]; then
                found_files="${found_files}${f} "
                # Check if this file was generated by our script
                if grep -q "$script_marker" "$f" 2>/dev/null; then
                    script_files="${script_files}${f} "
                else
                    other_files="${other_files}${f} "
                fi
                key_settings="${key_settings}${file_settings}\n"
            fi
        done
    fi
    
    if [ -n "$found_files" ]; then
        EXISTING_SYSCTL_SETTINGS="$key_settings"
        OTHER_SYSCTL_FILES="$other_files"
        print_banner "${ICON_GEAR} Existing sysctl configurations detected"
        
        # Show script-generated files
        if [ -n "$script_files" ]; then
            print_info "Generated by this script:"
            for f in $script_files; do
                echo -e "  ${GREEN}•${RESET} $f"
            done
        fi
        
        # Show other files
        if [ -n "$other_files" ]; then
            print_info "Other configurations:"
            for f in $other_files; do
                echo -e "  ${BLUE}•${RESET} $f"
            done
        fi
        
        echo ""
        print_info "Key settings currently active:"
        
        # Show important network/kernel settings
        local bbr_set qdisc_set forward_set
        bbr_set=$(echo -e "$key_settings" | grep -E 'tcp_congestion_control|tcp_bbr' | head -n3 || true)
        qdisc_set=$(echo -e "$key_settings" | grep -E 'default_qdisc' | head -n1 || true)
        forward_set=$(echo -e "$key_settings" | grep -E 'ip_forward|forwarding' | head -n3 || true)
        
        [ -n "$bbr_set" ] && echo -e "  ${GREEN}TCP Congestion:${RESET}\n$(echo "$bbr_set" | sed 's/^/    /')"
        [ -n "$qdisc_set" ] && echo -e "  ${GREEN}Queue Discipline:${RESET}\n$(echo "$qdisc_set" | sed 's/^/    /')"
        [ -n "$forward_set" ] && echo -e "  ${GREEN}IP Forwarding:${RESET}\n$(echo "$forward_set" | sed 's/^/    /')"
        
        # Count total settings
        local total_count
        total_count=$(echo -e "$key_settings" | grep -c '=' || echo 0)
        print_kv "Total settings" "$total_count parameters configured"
        echo ""
    fi
}

